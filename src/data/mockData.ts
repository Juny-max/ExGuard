// Helper to generate dates relative to today
export function getRelativeDateString(daysOffset: number): string {
  const date = new Date();
  date.setDate(date.getDate() + daysOffset);
  return date.toISOString().split('T')[0];
}

export function calculateDaysRemaining(expiryDateStr: string): number {
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  const expiry = new Date(expiryDateStr);
  expiry.setHours(0, 0, 0, 0);
  const diffTime = expiry.getTime() - today.getTime();
  return Math.ceil(diffTime / (1000 * 60 * 60 * 24));
}

export function determineStatus(daysRemaining: number, isDisposed: boolean = false, discountPct: number = 0): BatchStatus {
  if (isDisposed) return 'DISPOSED';
  if (daysRemaining < 0) return 'EXPIRED';
  if (discountPct > 0) return 'DISCOUNTED';
  if (daysRemaining <= 7) return 'CRITICAL_7';
  if (daysRemaining <= 14) return 'WARNING_14';
  if (daysRemaining <= 30) return 'WARNING_30';
  return 'SAFE';
}

